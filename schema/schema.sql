------------------------------------------------------------
-- 1. Drop existing objects
------------------------------------------------------------
DROP TABLE facility_image PURGE;
DROP TABLE building       PURGE;
DROP TABLE parking_area   PURGE;
DROP TABLE walkway        PURGE;
DROP TABLE green_space    PURGE;
DROP TABLE water_area     PURGE;

------------------------------------------------------------
-- 2. Clean geometry metadata for these tables
------------------------------------------------------------
DELETE FROM USER_SDO_GEOM_METADATA
 WHERE TABLE_NAME IN ('BUILDING','PARKING_AREA','WALKWAY','GREEN_SPACE','WATER_AREA');
COMMIT;

------------------------------------------------------------
-- 3. Spatial / relational tables (one per facility category)
------------------------------------------------------------
CREATE TABLE building (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(100) NOT NULL,
  use_type    VARCHAR2(50),
  description VARCHAR2(500),
  status      VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  geom        SDO_GEOMETRY  NOT NULL,
  CONSTRAINT ck_building_status
    CHECK (status IN ('ACTIVE','CLOSED','UNDER_CONSTRUCTION'))
);

CREATE TABLE parking_area (
  id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     VARCHAR2(100) NOT NULL,
  capacity NUMBER CHECK (capacity >= 0),
  geom     SDO_GEOMETRY NOT NULL
);

CREATE TABLE walkway (
  id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      VARCHAR2(100) NOT NULL,
  path_type VARCHAR2(30),
  geom      SDO_GEOMETRY NOT NULL
);

CREATE TABLE green_space (
  id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    VARCHAR2(100) NOT NULL,
  managed CHAR(1) DEFAULT 'Y' NOT NULL,
  geom    SDO_GEOMETRY NOT NULL,
  CONSTRAINT ck_green_space_managed CHECK (managed IN ('Y','N'))
);

CREATE TABLE water_area (
  id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100) NOT NULL,
  geom SDO_GEOMETRY NOT NULL
);

------------------------------------------------------------
-- 4. Multimedia table
-- No hard FK: facility_id references one of five tables depending on category.
-- The CHECK constraint plus the (category, facility_id) index + application
-- logic keep this honest.
------------------------------------------------------------
CREATE TABLE facility_image (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category    VARCHAR2(16) NOT NULL,
  facility_id NUMBER       NOT NULL,
  caption     VARCHAR2(500),
  uploaded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  image       ORDSYS.ORDImage,
  image_si    ORDSYS.SI_StillImage,
  image_ac    ORDSYS.SI_AverageColor,
  image_ch    ORDSYS.SI_ColorHistogram,
  image_pc    ORDSYS.SI_PositionalColor,
  image_tx    ORDSYS.SI_Texture,
  CONSTRAINT ck_facility_image_category CHECK (category IN
    ('BUILDING','PARKING_AREA','WALKWAY','GREEN_SPACE','WATER_AREA'))
);

