------------------------------------------------------------
-- 6. Spatial indexes
------------------------------------------------------------
CREATE INDEX idx_building_geom     ON building(geom)     INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX idx_parking_area_geom ON parking_area(geom) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX idx_walkway_geom      ON walkway(geom)      INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX idx_green_space_geom  ON green_space(geom)  INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX idx_water_area_geom   ON water_area(geom)   INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

------------------------------------------------------------
-- 7. Plain index for image lookups by owning facility
------------------------------------------------------------
CREATE INDEX idx_facility_image_fk ON facility_image(category, facility_id);
-- CampusAtlas: Multimedia Referential Integrity
-- Prevents images from referencing nonexistent facilities.

CREATE OR REPLACE TRIGGER trg_image_valid_facility
BEFORE INSERT OR UPDATE OF category, facility_id
ON facility_image
FOR EACH ROW

DECLARE
    v_id NUMBER;

BEGIN
    CASE :NEW.category

        WHEN 'BUILDING' THEN
            SELECT id INTO v_id
            FROM building
            WHERE id = :NEW.facility_id
            FOR UPDATE;

        WHEN 'PARKING_AREA' THEN
            SELECT id INTO v_id
            FROM parking_area
            WHERE id = :NEW.facility_id
            FOR UPDATE;

        WHEN 'WALKWAY' THEN
            SELECT id INTO v_id
            FROM walkway
            WHERE id = :NEW.facility_id
            FOR UPDATE;

        WHEN 'GREEN_SPACE' THEN
            SELECT id INTO v_id
            FROM green_space
            WHERE id = :NEW.facility_id
            FOR UPDATE;

        WHEN 'WATER_AREA' THEN
            SELECT id INTO v_id
            FROM water_area
            WHERE id = :NEW.facility_id
            FOR UPDATE;

        ELSE
            RAISE_APPLICATION_ERROR(
                -20002,
                'Invalid facility category'
            );

    END CASE;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20001,
            'Cannot attach image: facility does not exist'
        );
END;
/
-- Automatically delete a building's images
-- when the building is deleted.

CREATE OR REPLACE TRIGGER trg_building_delete_images
AFTER DELETE ON building
FOR EACH ROW

BEGIN
    DELETE FROM facility_image
    WHERE category = 'BUILDING'
      AND facility_id = :OLD.id;
END;
/
