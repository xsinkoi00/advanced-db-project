-- CampusAtlas — database schema
-- Phase 1 deliverable, due 2026-11-01.
--
-- Target: Oracle 18c (local XE and campus EE).
-- Run as the project user (locally: cardb @ XEPDB1).
--
-- Per the assignment, ORA-00942 ("table or view does not exist") on the DROP
-- statements below is expected and allowed on the first run.

------------------------------------------------------------
-- 1. Drop existing objects
------------------------------------------------------------
DROP TABLE facility_image PURGE;
DROP TABLE building       PURGE;
DROP TABLE parking_area   PURGE;
DROP TABLE walkway        PURGE;
DROP TABLE green_space    PURGE;
DROP TABLE water_area     PURGE;

------------------------------------------------------------
-- 2. Clean geometry metadata for these tables
------------------------------------------------------------
DELETE FROM USER_SDO_GEOM_METADATA
 WHERE TABLE_NAME IN ('BUILDING','PARKING_AREA','WALKWAY','GREEN_SPACE','WATER_AREA');
COMMIT;

------------------------------------------------------------
-- 3. Spatial / relational tables (one per facility category)
------------------------------------------------------------
CREATE TABLE building (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(100) NOT NULL,
  use_type    VARCHAR2(50),
  description VARCHAR2(500),
  status      VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  geom        SDO_GEOMETRY  NOT NULL,
  CONSTRAINT ck_building_status
    CHECK (status IN ('ACTIVE','CLOSED','UNDER_CONSTRUCTION'))
);

CREATE TABLE parking_area (
  id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     VARCHAR2(100) NOT NULL,
  capacity NUMBER CHECK (capacity >= 0),
  geom     SDO_GEOMETRY NOT NULL
);

CREATE TABLE walkway (
  id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      VARCHAR2(100) NOT NULL,
  path_type VARCHAR2(30),
  geom      SDO_GEOMETRY NOT NULL
);

CREATE TABLE green_space (
  id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    VARCHAR2(100) NOT NULL,
  managed CHAR(1) DEFAULT 'Y' NOT NULL,
  geom    SDO_GEOMETRY NOT NULL,
  CONSTRAINT ck_green_space_managed CHECK (managed IN ('Y','N'))
);

CREATE TABLE water_area (
  id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100) NOT NULL,
  geom SDO_GEOMETRY NOT NULL
);

------------------------------------------------------------
-- 4. Multimedia table
-- No hard FK: facility_id references one of five tables depending on category.
-- The CHECK constraint plus the (category, facility_id) index + application
-- logic keep this honest.
------------------------------------------------------------
CREATE TABLE facility_image (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category    VARCHAR2(16) NOT NULL,
  facility_id NUMBER       NOT NULL,
  caption     VARCHAR2(500),
  uploaded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  image       ORDSYS.ORDImage,
  image_si    ORDSYS.SI_StillImage,
  image_ac    ORDSYS.SI_AverageColor,
  image_ch    ORDSYS.SI_ColorHistogram,
  image_pc    ORDSYS.SI_PositionalColor,
  image_tx    ORDSYS.SI_Texture,
  CONSTRAINT ck_facility_image_category CHECK (category IN
    ('BUILDING','PARKING_AREA','WALKWAY','GREEN_SPACE','WATER_AREA'))
);

------------------------------------------------------------
-- 5. Geometry metadata (SRID NULL = local Cartesian plane)
--    Bounds and tolerance apply to the demonstration campus (0..1000 units,
--    5 mm tolerance equivalent).
------------------------------------------------------------
INSERT INTO USER_SDO_GEOM_METADATA VALUES ('BUILDING', 'GEOM',
  SDO_DIM_ARRAY(SDO_DIM_ELEMENT('X',-1000,1000,0.005), SDO_DIM_ELEMENT('Y',-1000,1000,0.005)), NULL);
INSERT INTO USER_SDO_GEOM_METADATA VALUES ('PARKING_AREA', 'GEOM',
  SDO_DIM_ARRAY(SDO_DIM_ELEMENT('X',-1000,1000,0.005), SDO_DIM_ELEMENT('Y',-1000,1000,0.005)), NULL);
INSERT INTO USER_SDO_GEOM_METADATA VALUES ('WALKWAY', 'GEOM',
  SDO_DIM_ARRAY(SDO_DIM_ELEMENT('X',-1000,1000,0.005), SDO_DIM_ELEMENT('Y',-1000,1000,0.005)), NULL);
INSERT INTO USER_SDO_GEOM_METADATA VALUES ('GREEN_SPACE', 'GEOM',
  SDO_DIM_ARRAY(SDO_DIM_ELEMENT('X',-1000,1000,0.005), SDO_DIM_ELEMENT('Y',-1000,1000,0.005)), NULL);
INSERT INTO USER_SDO_GEOM_METADATA VALUES ('WATER_AREA', 'GEOM',
  SDO_DIM_ARRAY(SDO_DIM_ELEMENT('X',-1000,1000,0.005), SDO_DIM_ELEMENT('Y',-1000,1000,0.005)), NULL);
COMMIT;

------------------------------------------------------------
-- 6. Spatial indexes
------------------------------------------------------------
CREATE INDEX idx_building_geom     ON building(geom)     INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX idx_parking_area_geom ON parking_area(geom) INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX idx_walkway_geom      ON walkway(geom)      INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX idx_green_space_geom  ON green_space(geom)  INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;
CREATE INDEX idx_water_area_geom   ON water_area(geom)   INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

------------------------------------------------------------
-- 7. Plain index for image lookups by owning facility
------------------------------------------------------------
CREATE INDEX idx_facility_image_fk ON facility_image(category, facility_id);

PROMPT CampusAtlas schema created successfully.
EXIT;
